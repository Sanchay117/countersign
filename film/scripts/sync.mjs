// The film draws with the site's own cheque component and stylesheet, so the two cannot drift
// apart. Copies ../src/app/ui/Cheque.tsx, guilloche.ts and ../src/app/globals.css into src/site/.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const app = join(root, '..', 'src', 'app');
const out = join(root, 'src', 'site');
mkdirSync(out, { recursive: true });

const note = '// Generated by scripts/sync.mjs from the site. Do not edit.\n';
writeFileSync(join(out, 'Cheque.tsx'), note + readFileSync(join(app, 'ui', 'Cheque.tsx'), 'utf8').replace('from "./guilloche"', 'from "./guilloche.ts"'));
writeFileSync(join(out, 'guilloche.ts'), note + readFileSync(join(app, 'ui', 'guilloche.ts'), 'utf8'));
writeFileSync(join(out, 'globals.css'), readFileSync(join(app, 'globals.css'), 'utf8'));
console.log('synced Cheque.tsx, guilloche.ts and globals.css');
